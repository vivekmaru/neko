export const THEME_BY_ID = Object.fromEntries(THEMES.map((t) => [t.id, t]));

export function applyTheme(theme: ThemeDef) {
  const r = document.documentElement;
  r.dataset.theme = theme.id;
  r.style.colorScheme = theme.group;
  const map: Record<string, string> = {
    "--bg": theme.bg,
    "--surface": theme.surface,
    "--surface-2": theme.surface2,
    "--fg": theme.fg,
    "--muted": theme.muted,
    "--subtle": theme.subtle,
    "--accent": theme.accent,
    "--accent-fg": theme.accentFg,
    "--red": theme.red,
    "--green": theme.green,
    "--yellow": theme.yellow,
    "--blue": theme.blue,
    "--cyan": theme.cyan,
    "--orange": theme.orange,
    "--magenta": theme.magenta,
  };
  for (const [k, v] of Object.entries(map)) r.style.setProperty(k, v);
}
